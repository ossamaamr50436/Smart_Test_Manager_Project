export type CountryOption = {
  code: string;
  name: string;
  ar: string;
  flag: string;
  dial: string;
};

/** قائمة كل دول العالم — مرتبة حسب رمز الاتصال */
export const COUNTRY_OPTIONS: CountryOption[] = (
  flags as Array<{ code: string; name: string; emoji: string }>
)
  .map((f) => ({
    code: f.code,
    name: f.name,
    ar: AR_COUNTRY_NAMES[f.code] ?? f.name,
    flag: f.emoji,
    dial: DIAL_CODES[f.code] ?? "+966",
  }))
  .sort(
    (a, b) =>
      Number(a.dial.slice(1)) - Number(b.dial.slice(1)) ||
      a.ar.localeCompare(b.ar, "ar")
  );

/** استنتاج الدولة من قيمة +966XXXXXXXXX */
export function countryFromValue(value: string): CountryOption {
  const digits = value.replace(/\D/g, "");
  let best: CountryOption | undefined;
  for (const c of COUNTRY_OPTIONS) {
    const prefix = c.dial.replace(/\D/g, "");
    if (digits.startsWith(prefix)) {
      // أطول رمز يطابق = الأدق (مثل +1 ثم +1268)
      if (!best || prefix.length > best.dial.replace(/\D/g, "").length) best = c;
    }
  }
  return best ?? COUNTRY_OPTIONS.find((c) => c.code === "SA")!;
}

/**
 * التحقق من رقم هاتف دولي صالح:
 * يبدأ بـ "+"، ثم أرقام فقط، بطول إجمالي 6-15 خانة (دون "+")
 */
export function validatePhoneE164(phone: string): boolean {
  if (!phone || !phone.startsWith("+")) return false;
  const digits = phone.slice(1);
  return /^\d+$/.test(digits) && digits.length >= 6 && digits.length <= 15;
}